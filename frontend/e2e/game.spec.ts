test('fundo estático e escolha de caminhos nas bordas sem retorno involuntário', async ({page}) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', {name: /Iniciar investigação/}).click();
  await expect(page.locator('#scene-loading')).toBeHidden({timeout: 30000});
  await page.locator('#read-journal').click();
  const canvas = page.locator('canvas');
  await expect(canvas).toHaveAttribute('width', '960');
  await expect(canvas).toHaveAttribute('height', '360');
  const gameID = await page.evaluate(() => localStorage.getItem('memorias-licantropicas:game'));
  const getWorld = async () => (await page.request.get(`/api/v1/games/${gameID}/world`)).json();
  const initial = await getWorld();
  expect(initial.location.width).toBe(960);
  const box = (await canvas.boundingBox())!;
  const clip = {x: Math.round(box.x + 45), y: Math.round(box.y + 25), width: 95, height: 45};
  const before = await page.screenshot({clip});
  await canvas.click();
  await page.keyboard.down('ArrowRight');
  await expect.poll(async () => (await getWorld()).player.x, {timeout: 8000}).toBeGreaterThan(270);
  await page.keyboard.up('ArrowRight');
  const after = await page.screenshot({clip});
  expect(after.equals(before)).toBeTruthy();

  await page.keyboard.down('ArrowLeft');
  await expect(page.locator('#exit-overlay')).toBeVisible({timeout: 8000});
  await page.keyboard.up('ArrowLeft');
  const links = initial.location.exits.filter((exit: {side: string}) => exit.side === 'left');
  await expect(page.locator('.exit-destination')).toHaveCount(links.length + 1);
  await expect(page.getByRole('button', {name: 'Ir para a outra ponta deste local'})).toBeVisible();
  await expect(page.locator('#exit-destinations button').first()).toBeFocused();
  await page.keyboard.press('ArrowUp');
  await expect(page.locator('#stay-here')).toBeFocused();
  await page.keyboard.press('Enter');
  await page.keyboard.down('ArrowLeft');
  await page.waitForTimeout(400);
  await expect(page.locator('#exit-overlay')).toBeHidden();
  await page.keyboard.up('ArrowLeft');
  await page.keyboard.down('ArrowRight');
  await expect.poll(async () => (await getWorld()).player.x, {timeout: 8000}).toBeGreaterThan(100);
  await page.keyboard.up('ArrowRight');
  await page.keyboard.down('ArrowLeft');
  await expect(page.locator('#exit-overlay')).toBeVisible({timeout: 8000});
  await page.keyboard.up('ArrowLeft');
  await page.screenshot({path: '../artifacts/game-exit-choices.png', fullPage: true});
  const firstDestination = page.locator('#exit-destinations button').first();
  await expect(firstDestination).toBeFocused();
  await firstDestination.dispatchEvent('keydown', {key: 'ArrowLeft', repeat: true});
  await expect(firstDestination).toBeFocused();
  await page.keyboard.press('ArrowDown');
  await expect(page.locator('#exit-destinations button').nth(1)).toBeFocused();
  await page.keyboard.press('ArrowUp');
  await page.keyboard.press('ArrowRight');
  await page.keyboard.press('ArrowLeft');
  await expect(firstDestination).toBeFocused();
  const responsePromise = page.waitForResponse(response => response.url().endsWith('/travel') && response.request().method() === 'POST');
  await page.keyboard.press('Enter');
  const response = await responsePromise;
  expect(response.status()).toBe(200);
  expect(response.request().postDataJSON().exit_side).toBe('left');
  const arrived = await response.json();
  expect(arrived.player.x).toBe(links[0].arrival_side === 'left' ? 96 : arrived.location.width - 96);
  await expect(page.locator('#exit-overlay')).toBeHidden();
  await expect(page.locator('#location-name')).toHaveText(arrived.location.name);
  await page.waitForTimeout(350);
  await expect(page.locator('#exit-overlay')).toBeHidden();
  await page.screenshot({path: '../artifacts/game-world-static.png', fullPage: true});
  await page.keyboard.down(arrived.player.x < arrived.location.width / 2 ? 'ArrowLeft' : 'ArrowRight');
  await expect(page.locator('#exit-overlay')).toBeVisible({timeout: 8000});
  await page.keyboard.up('ArrowLeft'); await page.keyboard.up('ArrowRight');
  const otherEndResponse = page.waitForResponse(response => response.url().endsWith('/travel') && response.request().method() === 'POST');
  await page.keyboard.press('ArrowUp');
  await page.keyboard.press('ArrowUp');
  await expect(page.getByRole('button', {name: 'Ir para a outra ponta deste local'})).toBeFocused();
  await page.keyboard.press('Enter');
  const otherEnd = await otherEndResponse;
  expect(otherEnd.status()).toBe(200);
  const wrapped = await otherEnd.json();
  expect(wrapped.location.id).toBe(arrived.location.id);
  expect(wrapped.player.x).toBe(arrived.player.x === 96 ? wrapped.location.width - 96 : 96);
  await expect(page.locator('#exit-overlay')).toBeHidden();
  expect(errors).toEqual([]);
});

